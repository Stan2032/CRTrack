// Turns the page's shared scripts (site/logic.js, site/stats.js) into modules the Worker can import,
// so the Discord bot makes exactly the same decisions as the leaders' page.
// Runs on every deploy (wrangler.jsonc "build"); tests/check.mjs fails if the copies are out of date.
// Usage: node worker/gen.mjs        (or --check to only compare)
import { readFileSync, writeFileSync } from 'node:fs';

const FILES = [['site/logic.js', 'worker/logic.gen.js'], ['site/stats.js', 'worker/stats.gen.js']];
const root = new URL('../', import.meta.url);

export function generate(src) {
  const line = src.match(/^if \(typeof module !== 'undefined'\) module\.exports = \{([^}]*)\};?\s*$/m);
  if (!line) throw new Error('no module.exports line');
  return '// GENERATED by worker/gen.mjs from the site script. Do not edit.\n'
    + src.replace(line[0], `export {${line[1]}};\n`);
}

export function outOfDate() {
  return FILES.filter(([from, to]) => {
    let have = ''; try { have = readFileSync(new URL(to, root), 'utf8'); } catch (e) {}
    return have !== generate(readFileSync(new URL(from, root), 'utf8'));
  }).map(f => f[1]);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) { const bad = outOfDate(); if (bad.length) { console.error('Out of date:', bad.join(', ')); process.exit(1); } }
  else for (const [from, to] of FILES) writeFileSync(new URL(to, root), generate(readFileSync(new URL(from, root), 'utf8')));
}
